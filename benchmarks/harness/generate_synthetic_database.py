#!/usr/bin/env python3
"""Generate a deterministic synthetic mixed-family MMDB; no external dependencies."""
import hashlib
import json
import random
from pathlib import Path


def control(kind, size):
    if size < 29:
        return bytes([(kind << 5) | size])
    if size < 285:
        return bytes([(kind << 5) | 29, size - 29])
    raise ValueError(size)


def string(s):
    b = s.encode()
    return control(2, len(b)) + b


def number(n, kind=6):
    b = n.to_bytes(max(1, (n.bit_length() + 7) // 8), 'big')
    return control(kind, len(b)) + b


def mapping(items):
    return control(7, len(items)) + b''.join(string(k) + v for k, v in items)


def generate(path):
    rng = random.Random(0x4D4D4442)
    nodes = [[None, None]]
    records = []
    prefixes = []
    for family in (4, 6):
        for _ in range(32768):
            bits = rng.choice((16, 20, 24, 28, 32) if family == 4 else (16, 24, 32, 48, 64))
            address = rng.getrandbits(32 if family == 4 else 128)
            width = bits + (96 if family == 4 else 0)
            if family == 4:
                address &= 0xffffffff
            node = 0
            for depth in range(width):
                bit = (address >> (127 - depth)) & 1
                child = nodes[node][bit]
                if depth == width - 1:
                    if child is None:
                        ident = len(records) + 1
                        nodes[node][bit] = -ident
                        records.append(mapping([('id', number(ident)), ('label', string('network-%08x' % ident))]))
                        prefixes.append([family, hex(address), width])
                    break
                if child is not None and child < 0:
                    break
                if child is None:
                    child = len(nodes)
                    nodes[node][bit] = child
                    nodes.append([None, None])
                node = child
    count = len(nodes)
    offsets = []
    data = bytearray()
    for record in records:
        offsets.append(len(data))
        data.extend(record)
    tree = bytearray()
    for pair in nodes:
        l, r = [count if n is None else count + 16 + offsets[-n - 1] if n < 0 else n for n in pair]
        assert max(l, r) < 2**28
        tree.extend(l.to_bytes(4, 'big')[1:])
        tree.append(((l >> 24) << 4) | (r >> 24))
        tree.extend(r.to_bytes(4, 'big')[1:])
    meta = mapping([
        ('node_count', number(count)), ('record_size', number(28, 5)),
        ('ip_version', number(6, 5)), ('database_type', string('Synthetic-Performance')),
        ('languages', b'\x00\x04'),
        ('binary_format_major_version', number(2, 5)),
        ('binary_format_minor_version', number(0, 5)),
        ('build_epoch', b'\x04\x02\x65\x53\xf1\x00'),
        ('description', mapping([('en', string('Deterministic synthetic lookup benchmark'))])),
    ])
    # Extended uint64: control size=4, extended type=9-7=2.
    blob = bytes(tree) + bytes(16) + bytes(data) + b'\xab\xcd\xefMaxMind.com' + meta
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(blob)
    manifest = dict(path=str(path), sha256=hashlib.sha256(blob).hexdigest(), bytes=len(blob),
                    node_count=count, records=len(records), record_size=28, ip_version=6,
                    generator_seed=0x4D4D4442, attempts_per_family=32768,
                    provenance='Generated by benchmarks/harness/generate_synthetic_database.py using Python random.Random',
                    limitation='Synthetic distribution; no commercial GeoIP database available. Not representative of every deployed database.')
    path.with_suffix('.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps(manifest))


if __name__ == '__main__':
    import sys
    generate(Path(sys.argv[1] if len(sys.argv) > 1 else 'benchmarks/artifacts/campaign/data/synthetic.mmdb'))
